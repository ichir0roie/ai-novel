#!/usr/bin/env python3
"""人物の筋書き(`CharacterPlot`)の書き方のルール。

人物を生む側(`random_character_generator.py`)と、出来事の中で筋書きを
足す側(`event_progression_generator.py`)の両方が同じ文面を使う。
出来事側だけ短い指示にしていたため、追加される筋書きが一文で終わっていた
(2026-09 の観測)。
"""
from __future__ import annotations

CHARACTER_PLOT_INSTRUCTION = """\
筋書き(plot / text)は、この一件について今後たどってほしい道筋。
人物の説明と矛盾しない範囲で、起・承・転・結の四つの段階を、この順に、それぞれ一〜二文ずつ改行で区切って書く。
起は、今の立場と、抱えている問題・欲求。
承は、その問題・欲求が誰と何を巡ってどう広がるか。
転は、それを決定的に動かす転機(対立・裏切り・喪失・選択など)。
結は、その転機を経てどこに行き着くか(成功・失敗・変質、どれでもよい)。
起だけを書いて終わらせず、四つの段階を必ず全部埋める。
各段階は、誰と・何を巡って、が分かる具体的な内容にする。
出来事生成のたびに読まれ、関わる出来事の展開の優先材料になる。"""


def plot_span_instruction(years: int) -> str:
    """`years` 年かけてたどる筋書きとして書かせるための一文。"""
    return f"""\
この筋書きは、いまから約{years}年かけて結まで至るものとして書く。
起・承・転・結の間隔と、各段階で起きることの大きさを、この長さに見合ったものにする(短ければ身近で速い変化、長ければ世代や立場が変わるほどのゆっくりした変化)。"""


PLOT_PACING_INSTRUCTION = """\
plot には期間(start〜end)が付いている。
end はその筋書きが結に至る予定の時点で、いまが期間のどのあたりかで段階を測る。
期間の序盤なら起・承に留め、転・結を急がせない。
期間の終わりが近づいて初めて転・結へ向かう出来事を起こす。"""
