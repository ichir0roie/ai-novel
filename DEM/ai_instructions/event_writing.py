#!/usr/bin/env python3
"""出来事(`Event`)の書き方・進め方のルールを持つ、正本。

Claude が `commit_event` の `text` を書くときも、`DEM/local_ai/`(`ai_client`
を介してローカル AI が db への確定まで一気に行う `time_keeper` の常駐ループ)
が `event_progression_generator.py` / `character_lifespan.py` で出来事を
生成するときも、**ここに書いた定数の文面をそのまま基準にする。**

`IHG/chronicle.md` にはこのルールの散文(なぜこの形にしたか)だけを置き、
文面そのものはここへ寄せてある。**ルールの文面を変えるときはここだけを
直す。** `IHG/chronicle.md` 側は、ここを指す参照と背景説明のままにする
(散文を変えたくなったら、そちらも合わせて見直す)。

`naming.py` `principles.py` は逆に、対話の中で人間(Claude)が手順を踏む
前提の長い IHG 文書から、常駐ループ向けに要旨だけを抜き出した簡略版
(そちらは `IHG/*.md` が正本のまま)。この違いは、`IHG/chronicle.md`
「出来事の text は場面で書く」の节にも明記してある。
"""
from __future__ import annotations

# 出来事を考えるとき、判断材料として渡す「直近の出来事」の件数。
# 件数を増やすほど、過去に使った比喩や語彙がそのまま次の出来事へ持ち越され、
# 同じ人物・同じ場所の中で語彙が自己増殖していく。2 件程度にとどめることで、
# 直前の文脈は踏まえつつ、語彙が固定化・肥大化するのを防ぐ。
RECENT_EVENT_LIMIT = 2

# 人物の text に追記できる件数(生成時の基礎説明1件 + ここで数える追記件数)。
# text は上書きせず積み足す設計(CHARACTER_TEXT_UPDATE_INSTRUCTION)だが、
# 上限が無いと一度紛れ込んだ比喩・語彙が消えずに、その人物が関わる全ての
# 将来の生成へ永久に持ち込まれ続ける(RECENT_EVENT_LIMIT が出来事の一覧を
# 絞るのと同じ理由。ただしこちらは出来事一覧を絞るだけでは防げない別経路)。
# 生成時の基礎説明(先頭の一段)は常に残し、直近の追記だけをこの件数まで
# 保持する(`CHARACTER_NOTE_SEPARATOR` で区切って数える)。
CHARACTER_NOTE_LIMIT = 5
CHARACTER_NOTE_SEPARATOR = "\n---\n"

EVENT_SCENE_INSTRUCTION = (
    "text は「起きたことの要約」ではない。「〜という出来事があった」の"
    "一文で済ませず、軽い小説として1000文字程度で、その時その場のキャラク"
    "ターの思考・行動・(この出来事が及ぼす)影響を場面として書く。"
    "この場所・この人物自身に固有の、渡された環境・産業・人間関係・地名の"
    "うち少なくとも一つを、実際に text の描写の中で具体的に使う。"
    "誰が・何が引き起こしたのかを名指しせず、雰囲気やムードだけで状況を"
    "漂わせる書き方を避け、渡された固有の情報から出来事を立てる。"
    "文体は説明文にせず、改行を惜しまず1〜4行程度の段落で区切る。"
    "「町が」「時代が」のようなキャラクター不在の主語で状況を語るのではなく、"
    "そのときキャラクターが何を感じ、何を見て、何を思うかを中心に書く。"
)

EVENT_PROGRESSION_INSTRUCTION = (
    "直近の出来事の一覧(名前・種別)を先に見て、同じ関係者・同じ場所で、"
    "前回までと似た種別の出来事の結末(確認する・合意する、など)を、名前"
    "だけ変えてそのまま繰り返さない。前回までに積み上がった対立・決定を"
    "土台にして、状況を具体的に一歩動かす(決着する・破られる・第三者が"
    "絡む・決定的な行動に出る、など)か、関わる相手・題材を変える。"
    "新しい出来事が起きることは前提であり、event_name を空のまま返す"
    "選択肢は無い。必ず1件、次の一歩になる出来事を決めて返す。"
)

EVENT_DURATION_INSTRUCTION = (
    "event_duration_days(この出来事の影響が続く日数の整数。関わった人物・"
    "個体は、この日数のあいだ進行中として次の出来事の対象から外れる。"
    "立ち話や単発の判断なら1、旅・対立の膠着・準備のように長く尾を引く"
    "ものなら30〜90程度など、内容に見合う値を1〜90の範囲で決める)"
)

CHARACTER_TEXT_UPDATE_INSTRUCTION = (
    "text は、この出来事を通して見えた、その人物の性格・信念・人となり"
    "(パーソナリティ)についてだけ短く一言で書く。状況の要約や現在の状態"
    "(場所・立場・置かれている状況など)は書かない。この出来事でその人物の"
    "パーソナリティについて新しく分かったことが無ければ、この人物自体を"
    "character_updates に含めない。書いた内容は既存の text の続きに積み"
    "足されるので、それだけで意味が通る一文にする。"
)
