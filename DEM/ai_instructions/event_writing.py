#!/usr/bin/env python3
"""出来事(`Event`)の書き方・進め方のルールを持つ、正本。

Claude が `commit_event` の `text` を書くときも、`DEM/local_ai/`(`ai_client`
を介してローカル AI が db への確定まで一気に行う `time_keeper` の常駐ループ)
が `event_progression_generator.py` / `character_lifespan.py` で出来事を
生成するときも、**ここに書いた定数の文面をそのまま基準にする。**

**出来事の `text` は小説ではなく、情報整理のための記録。** 実際のストーリー
(本文)は話(`Episode`)の側で別に書くので、出来事で文体・セリフの言い回しを
決めない。出来事が持つのは、物事がどう変わったか・人物が何を感じたか・誰と
どの組織が何をしたか、という後から引ける中身だけ。

`IHG/chronicle.md` にはこのルールの散文(なぜこの形にしたか)だけを置き、
文面そのものはここへ寄せてある。**ルールの文面を変えるときはここだけを
直す。** `IHG/chronicle.md` 側は、ここを指す参照と背景説明のままにする
(散文を変えたくなったら、そちらも合わせて見直す)。

`naming.py` `principles.py` は逆に、対話の中で人間(Claude)が手順を踏む
前提の長い IHG 文書から、常駐ループ向けに要旨だけを抜き出した簡略版
(そちらは `IHG/*.md` が正本のまま)。この違いは、`IHG/chronicle.md`
「出来事の text は記録として書く」の節にも明記してある。
"""
from __future__ import annotations

# 出来事を考えるとき、判断材料として渡す「直近の出来事」の件数。
# 件数を増やすほど、過去に使った比喩や語彙がそのまま次の出来事へ持ち越され、
# 同じ人物・同じ場所の中で語彙が自己増殖していく。2 件程度にとどめることで、
# 直前の文脈は踏まえつつ、語彙が固定化・肥大化するのを防ぐ。
RECENT_EVENT_LIMIT = 2

# 人物・個体の text に追記できる件数(生成時の基礎説明1件 + ここで数える追記件数)。
# text は上書きせず積み足す設計(CHARACTER_TEXT_UPDATE_INSTRUCTION /
# OBJECT_TEXT_UPDATE_INSTRUCTION)だが、
# 上限が無いと一度紛れ込んだ比喩・語彙が消えずに、その人物・個体が関わる全ての
# 将来の生成へ永久に持ち込まれ続ける(RECENT_EVENT_LIMIT が出来事の一覧を
# 絞るのと同じ理由。ただしこちらは出来事一覧を絞るだけでは防げない別経路)。
# 生成時の基礎説明(先頭の一段)は常に残し、直近の追記だけをこの件数まで
# 保持する(`CHARACTER_NOTE_SEPARATOR` で区切って数える)。人物と個体で
# 同じ上限・同じ区切りを使う。
CHARACTER_NOTE_LIMIT = 5
CHARACTER_NOTE_SEPARATOR = "\n---\n"

EVENT_RECORD_INSTRUCTION = (
    "text は小説ではなく、世界に何が起きて何が変わったかを後から引くための"
    "記録として書く。情景描写・比喩・セリフ・語り口は書かない。誰がどんな"
    "言い回しで喋ったかは本文(ストーリー)の側で決めるので、ここでは決めない。"
    "次の四つを、この順に、それぞれ改行で区切った短い段落として書く。"
    "(1)発端: 何がきっかけで動いたか。渡された場所・環境・資源・産業・"
    "人間関係・地名のうち少なくとも一つを名指しで使う。"
    "(2)行動: 誰が何をしたか。人物と、国・組織・集団などの個体それぞれを"
    "主語に立てて、一件ずつ分けて書く。"
    "(3)感情: 関わった人物が、何に対してどう感じ、何を望み、何を恐れたか。"
    "誰の感情かを名指しで書く。"
    "(4)変化と影響: この出来事の前と後で何がどう変わったか"
    "(立場・所属・取り決め・資源の量・力関係・居場所など)と、"
    "そのうち何がこの先も残るか。"
    "分かるところは、数・期間・物の名前・場所の名前・人物の名前を具体的に"
    "書き込む。状況を雰囲気で漂わせず、事実と関係で書く。"
    "全体で400〜800文字程度。"
)

EVENT_RELATION_INSTRUCTION = (
    "出来事は、その時その場にあるもの同士の相互関係から立てる。"
    "渡された人物・個体(国・組織・集団・物)・場所・資源のうち二つ以上を"
    "必ず噛み合わせ、どちらがどちらに働きかけ、相手がどう応じたかを書く。"
    "一人(一個体)だけで完結する出来事にしない。"
)

OBJECT_ACTION_INSTRUCTION = (
    "国・組織・軍・商会・氏族のような個体は、背景ではなく行為の主体として"
    "扱う。居合わせる個体があるなら、そのうち少なくとも一つについて、"
    "何を決め、何を動かし、誰に対して働きかけたかを、その個体の名前を"
    "主語にして書く。人物の側は、その決定に従う・背く・利用する・取り引き"
    "する、といった個体との関係で書く。"
)

EVENT_PROGRESSION_INSTRUCTION = (
    "直近の出来事の一覧(名前)を先に見て、同じ関係者・同じ場所で、"
    "前回までと似た内容・結末(確認する・合意する、など)を、名前"
    "だけ変えてそのまま繰り返さない。「話し合って合意する」「対立したまま"
    "膠着する」という**決着の付け方そのもの**も、同じ内輪の顔ぶれだけで"
    "何度も使い回さない。前回までに積み上がった対立・決定を土台にして、"
    "状況を具体的に一歩動かす(決着する・破られる・第三者が絡む・決定的な"
    "行動に出る、など)か、関わる相手・題材を変える。同じ内輪の関係者だけで"
    "出来事が何度も閉じているなら、内輪の合意・対立では止められない外的な"
    "圧力・利害を持ち込む一歩として、渡された「一つ上の圏内の個体」から"
    "新たに関与させるか、それでも噛み合う主体が見当たらないときに限って"
    "object_founded で新しい個体を誕生させ、それを当事者として関与させる。"
    "新しい出来事が起きることは前提であり、event_name を空のまま返す"
    "選択肢は無い。必ず1件、次の一歩になる出来事を決めて返す。"
)

EVENT_DURATION_INSTRUCTION = (
    "event_duration_days(この出来事の影響が続く日数の整数。関わった人物・"
    "個体は、この日数のあいだ進行中として次の出来事の対象から外れる。"
    "立ち話や単発の判断なら1、旅・対立の膠着・準備のように長く尾を引く"
    "ものなら30〜90程度など、内容に見合う値を1〜90の範囲で決める)"
)

CHARACTER_TEXT_UPDATE_INSTRUCTION = (
    "text は、この出来事を通して見えた、その人物の性格・信念・人となり"
    "(パーソナリティ)についてだけ短く一言で書く。状況の要約や現在の状態"
    "(場所・立場・置かれている状況など)は書かない。この出来事でその人物の"
    "パーソナリティについて新しく分かったことが無ければ、この人物自体を"
    "character_updates に含めない。書いた内容は既存の text の続きに積み"
    "足されるので、それだけで意味が通る一文にする。"
)

OBJECT_TEXT_UPDATE_INSTRUCTION = (
    "text は、この出来事を通して見えた、その個体(国・組織・集団・物)の"
    "性質・方針・立場についてだけ短く一言で書く。その場の状況の要約は"
    "書かない。この出来事でその個体について新しく分かったことが無ければ、"
    "この個体自体を object_updates に含めない。書いた内容は既存の text の"
    "続きに積み足されるので、それだけで意味が通る一文にする。"
)
