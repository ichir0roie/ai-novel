#!/usr/bin/env python3
"""`IHG/naming.md` の要点を、AI へのプロンプトに埋め込める形に切り出したもの。

`IHG/naming.md` は人間(Claude)が対話の中で判断する前提の長い手順書で、
乱数で言語を一つ引いてから固有名詞を組み立てる、といった対話越しの手順は
そのままでは JSON 生成 1 回で名づけを終える場面(`DEM/local_ai/` の常駐
ループ)に埋め込めない。ここでは、Claude が手順を踏んで名づけるときと同じ
基準を、ローカル AI にもプロンプト経由で一括で守らせるために、naming.md の
要旨だけを定数として持つ。

**Claude 自身が名づけるとき**(`CreateRandomCharacter` `CreateRandomPlace`
などの下書きに名を付けるとき)は、この定数ではなく `IHG/naming.md` を直接
読んで手順(乱数で言語を引く等)を踏む。ここに切り出した定数は、手順を
踏めないローカル AI 向けの簡略版でしかない。

**`IHG/naming.md` の基準を変えたら、ここも合わせて直す。**
"""
from __future__ import annotations

import re

# 名前をまだ決めていない・確定済みの名前を AI に書き写させたくない場面で、
# 本文中でその一件を指すのに使う仮置き。名前が決まった後、この文字列を
# 確定した name へ機械的に置き換える(AI に名前そのものを書かせて、綴りが
# name の記録とずれるのを避けるため)。
NAME_PLACEHOLDER = "【名前】"

# ローカルAIは括弧の種類・内側の空白まで指示通りに再現するとは限らないため、
# 「名前」を囲む括弧の表記ゆれ(全角/半角、前後の空白)は許容して拾う。
# 括弧の無い裸の「名前」は普通の日本語としても出現しうるので対象にしない。
_NAME_PLACEHOLDER_PATTERN = re.compile(r"[【\[(]\s*名前\s*[】\])]")


def fill_name_placeholder(text: str, name: str) -> str:
    """`text` 中の `NAME_PLACEHOLDER`(括弧の表記ゆれを含む)を、確定した `name` へ機械的に置き換える。"""
    return _NAME_PLACEHOLDER_PATTERN.sub(name, text)


